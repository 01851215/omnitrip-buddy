/** Fast prefix-first city search — starts-with scored higher than contains. */
export function searchCities(query: string, limit = 8): WorldCity[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];

  const results: Array<{ city: WorldCity; score: number }> = [];

  for (const city of worldCities) {
    const name    = city.name.toLowerCase();
    const country = city.country.toLowerCase();

    let score = 0;
    if (name.startsWith(q))         score = 10;
    else if (country.startsWith(q)) score = 6;
    else if (name.includes(q))      score = 3;
    else if (country.includes(q))   score = 1;

    if (score > 0) results.push({ city, score });
  }

  return results
    .sort((a, b) => b.score - a.score || a.city.name.localeCompare(b.city.name))
    .slice(0, limit)
    .map((r) => r.city);
}
